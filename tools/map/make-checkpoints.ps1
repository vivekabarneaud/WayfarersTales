# Wayfarer's Tales - check points for the map page (tools/map/index.html).
# Positions measured in game: your Homework notes (saved data) and the addon's spots
# (SensesData.lua, More.lua). Written to checkpoints.js (not in git: it comes from your play).
# Run:  powershell -ExecutionPolicy Bypass -File tools\map\make-checkpoints.ps1

$ErrorActionPreference = "Stop"
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$repo = Resolve-Path (Join-Path $here "..\..")
$wtf = "C:\Program Files (x86)\World of Warcraft\_forever_\WTF\Account"
$utf8 = New-Object System.Text.UTF8Encoding($false)
$points = New-Object System.Collections.Generic.List[object]
$seen = @{}

function Add-Point($zone, $x, $y, $label, $src) {
  $key = "$zone|$x|$y"
  if ($seen.ContainsKey($key)) { return }
  $seen[$key] = $true
  $points.Add([ordered]@{ zone = [int]$zone; x = [double]$x; y = [double]$y; label = $label; src = $src })
}

# 1. Homework notes: { ["mapID"] = 1429, ["x"] = 43.8, ["y"] = 65.9, ["text"] = "...", ["sub"] = "..." }
$saved = Get-ChildItem -Path $wtf -Recurse -Include "WayfarersTales.lua", "WayfarersTales.lua.bak" -ErrorAction SilentlyContinue
foreach ($f in $saved) {
  $lines = [System.IO.File]::ReadAllLines($f.FullName, $utf8)
  $i = [array]::IndexOf($lines, '["fieldNotes"] = {')
  if ($i -lt 0) { continue }
  # the whole fieldNotes table: count braces (one key per line in saved files)
  $depth = 1; $buf = New-Object System.Text.StringBuilder
  for ($j = $i + 1; $j -lt $lines.Length -and $depth -gt 0; $j++) {
    $l = $lines[$j]
    if ($l -match '\{$') { $depth++ } elseif ($l -match '^\s*\},?$') { $depth-- }
    [void]$buf.AppendLine($l)
  }
  foreach ($note in ($buf.ToString() -split "`n\{")) {
    $m = [regex]::Match($note, '\["mapID"\] = (\d+)'); if (-not $m.Success) { continue }
    $x = [regex]::Match($note, '\["x"\] = ([\d.]+)'); $y = [regex]::Match($note, '\["y"\] = ([\d.]+)')
    if (-not ($x.Success -and $y.Success)) { continue }
    $t = [regex]::Match($note, '\["text"\] = "((?:[^"\\]|\\.)*)"').Groups[1].Value -replace '\\"', '"'
    $sub = [regex]::Match($note, '\["sub"\] = "((?:[^"\\]|\\.)*)"').Groups[1].Value
    if ($t.Length -gt 70) { $t = $t.Substring(0, 67) + "..." }
    $label = if ($sub) { "Note ($sub): $t" } else { "Note: $t" }
    Add-Point $m.Groups[1].Value $x.Groups[1].Value $y.Groups[1].Value $label "note"
  }
}

# 2. The addon's spots: { id = "wf_sentinel_inn", map = 1436, x = 52.5, y = 53.1, ... } or { map = ..., name = "..." }
foreach ($name in "SensesData.lua", "More.lua") {
  $text = [System.IO.File]::ReadAllText((Join-Path $repo $name), $utf8)
  foreach ($m in [regex]::Matches($text, '\{\s*(?:id = "([^"]+)",\s*)?map = (\d+), x = ([\d.]+), y = ([\d.]+)(?:[^\n]*?name = "([^"]+)")?')) {
    $label = if ($m.Groups[1].Success) { "Spot: " + $m.Groups[1].Value } elseif ($m.Groups[5].Success) { "Spot: " + $m.Groups[5].Value } else { "Spot" }
    Add-Point $m.Groups[2].Value $m.Groups[3].Value $m.Groups[4].Value $label "spot"
  }
}

$json = ($points | ForEach-Object { $_ | ConvertTo-Json -Compress }) -join ",`n "
$out = "// Generated by make-checkpoints.ps1: positions measured in game (not in git).`nwindow.WT_CHECKPOINTS = [`n $json`n];`n"
[System.IO.File]::WriteAllText((Join-Path $here "checkpoints.js"), $out, $utf8)
Write-Output ("{0} check points written to checkpoints.js" -f $points.Count)
