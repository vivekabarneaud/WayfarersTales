# Wayfarer's Tales - turns the approved regions of tools/map/regions.js into RegionsData.lua
# (the addon's data: each region's painted cells, temperature, flags and lines).
# Only regions with status "approved" and a "final" go in. Run it after approving regions:
#   powershell -NoProfile -ExecutionPolicy Bypass -File tools/map/make-regions.ps1
# Every line goes in as a draft (it plays only with "Try new lines" on) until it's been seen in game.

$src = Join-Path $PSScriptRoot "regions.js"
$out = Join-Path (Split-Path $PSScriptRoot -Parent | Split-Path -Parent) "RegionsData.lua"
$utf8 = New-Object System.Text.UTF8Encoding($false)
$inv = [Globalization.CultureInfo]::InvariantCulture

$text = [System.IO.File]::ReadAllText($src, $utf8)
$data = $text.Substring($text.IndexOf("{"), $text.LastIndexOf("}") - $text.IndexOf("{") + 1) | ConvertFrom-Json

function LuaString([string]$s) {
  return '"' + $s.Replace('\', '\\').Replace('"', '\"').Replace("`r", '').Replace("`n", '\n') + '"'
}

# A JSON value as a Lua value: true/false, numbers, strings, lists and tables (the "when" conditions)
function ToLua($v) {
  if ($null -eq $v) { return "nil" }
  if ($v -is [bool]) { if ($v) { return "true" } else { return "false" } }
  if ($v -is [string]) { return LuaString $v }
  if ($v -is [int] -or $v -is [long] -or $v -is [double] -or $v -is [decimal]) { return $v.ToString($inv) }
  if ($v -is [array]) { return "{ " + ((@($v) | ForEach-Object { ToLua $_ }) -join ", ") + " }" }
  $parts = @()
  foreach ($p in $v.PSObject.Properties) {
    if ($p.Name -notmatch '^[A-Za-z_][A-Za-z0-9_]*$') { throw "Unexpected key in a condition: $($p.Name)" }
    $parts += "$($p.Name) = $(ToLua $p.Value)"
  }
  return "{ " + ($parts -join ", ") + " }"
}

$kinds = @("arrive", "ambient", "goIn", "hour", "yell")
$zones = [ordered]@{}
$count = 0; $lineCount = 0
foreach ($r in $data.regions) {
  if ($r.status -ne "approved" -or -not $r.final) { continue }
  $f = $r.final
  $b = New-Object System.Text.StringBuilder
  [void]$b.Append("    { id = $(LuaString $r.id), name = $(LuaString $r.name),`n")
  [void]$b.Append("      cells = $(LuaString $r.cells),`n")
  $extra = @()
  if ($null -ne $f.air) { $extra += "air = $(ToLua $f.air)" }
  if ($null -ne $f.water) { $extra += "water = $(ToLua $f.water)" }
  if ($f.abandoned) { $extra += "abandoned = true" }
  if ($extra.Count) { [void]$b.Append("      " + ($extra -join ", ") + ",`n") }
  foreach ($k in $kinds) {
    $lines = @($f.lines | Where-Object { $_.on -eq $k })
    if (-not $lines.Count) { continue }
    [void]$b.Append("      $k = {`n")
    foreach ($l in $lines) {
      $when = if ($l.when) { ", when = $(ToLua $l.when)" } else { "" }
      [void]$b.Append("        { draft = true$when,`n          en = $(LuaString $l.en),`n          fr = $(LuaString $l.fr) },`n")
      $lineCount++
    }
    [void]$b.Append("      },`n")
  }
  foreach ($l in @($f.lines)) { if ($kinds -notcontains $l.on) { throw "Region $($r.name): unknown trigger '$($l.on)'" } }
  [void]$b.Append("    },`n")
  $z = [string]$r.zone
  if (-not $zones.Contains($z)) { $zones[$z] = @() }
  $zones[$z] += $b.ToString()
  $count++
}

$lua = New-Object System.Text.StringBuilder
[void]$lua.Append("-- Wayfarer's Tales - painted map regions. GENERATED by tools/map/make-regions.ps1 from`n")
[void]$lua.Append("-- tools/map/regions.js (approved regions only): don't edit by hand, change the cards and run it again.`n")
[void]$lua.Append("-- By zone map ID. cells = the painted area (see World.lua), air / water = degrees added,`n")
[void]$lua.Append("-- abandoned = nobody lives here. Lines: arrive (first time), ambient, goIn (stepping into a house),`n")
[void]$lua.Append("-- hour (the game clock strikes a new hour), yell (an NPC shouts nearby).`n`n")
[void]$lua.Append("local _, KT = ...`nlocal D = KT.Data`n`nD.REGIONS = {`n")
foreach ($z in $zones.Keys) {
  [void]$lua.Append("  [$z] = {`n")
  foreach ($s in $zones[$z]) { [void]$lua.Append($s) }
  [void]$lua.Append("  },`n")
}
[void]$lua.Append("}`n")
[System.IO.File]::WriteAllText($out, $lua.ToString(), $utf8)
"{0} regions, {1} lines -> {2}" -f $count, $lineCount, $out
